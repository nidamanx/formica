"""Generates the Formica launcher icon in every format from art/formica_art.py.

Usage: python3 art/generate_icon.py
Needs shapely (Debian: python3-shapely) for the monochrome layers and cairosvg (Debian:
python3-cairosvg) for the store PNG.
Outputs:
- app/src/main/res: adaptive icon (mipmap-anydpi), colour foreground, monochrome layer for
  themed icons (Android 13+), background colour; the welcome screen shows the foreground too;
- app/src/debug/res: the same for debug builds ("Formica-D"): draft greys and a "D" badge,
  also in the monochrome layer, so themed icons tell the two apps apart;
- art/icon.svg and fastlane/metadata/android/en-US/images/icon.png (512x512).
"""
import math
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ in art/ when importing formica_art

from shapely import affinity
from shapely.geometry import LineString, MultiPolygon, Point, Polygon, box
from shapely.ops import unary_union

import formica_art as art

ROOT = Path(__file__).resolve().parent.parent
SVG_NS = "{http://www.w3.org/2000/svg}"
HEADER = "<!-- Generated by art/generate_icon.py: do not edit by hand -->"
CURVE_STEPS = 16


def transforms(text):
    """SVG transform list, outermost first: [("translate", [x, y]), ("rotate", [a, cx, cy])...]."""
    return [(name, [float(v) for v in re.split(r"[ ,]+", args.strip())])
            for name, args in re.findall(r"(\w+)\(([^)]*)\)", text or "")]


def shape_path(el):
    """Path data of a basic shape, with the arcs Android vectors understand."""
    tag = el.tag.replace(SVG_NS, "")
    f = lambda name: float(el.get(name, 0))
    if tag == "path":
        return " ".join(el.get("d").split())
    if tag in ("circle", "ellipse"):
        cx, cy = f("cx"), f("cy")
        rx = f("r") if tag == "circle" else f("rx")
        ry = f("r") if tag == "circle" else f("ry")
        return (f"M{cx - rx:g},{cy:g} A{rx:g},{ry:g} 0 1,0 {cx + rx:g},{cy:g} "
                f"A{rx:g},{ry:g} 0 1,0 {cx - rx:g},{cy:g} Z")
    if tag == "rect":
        x, y, w, h, r = f("x"), f("y"), f("width"), f("height"), f("rx")
        if r == 0:
            return f"M{x:g},{y:g} H{x + w:g} V{y + h:g} H{x:g} Z"
        return (f"M{x + r:g},{y:g} H{x + w - r:g} A{r:g},{r:g} 0 0,1 {x + w:g},{y + r:g} "
                f"V{y + h - r:g} A{r:g},{r:g} 0 0,1 {x + w - r:g},{y + h:g} H{x + r:g} "
                f"A{r:g},{r:g} 0 0,1 {x:g},{y + h - r:g} V{y + r:g} A{r:g},{r:g} 0 0,1 {x + r:g},{y:g} Z")
    raise ValueError(f"unsupported element {tag}")


# ---------- Android vector drawable (colour layers) ----------

def argb(colour, opacity=1.0):
    return f"#{round(opacity * 255):02X}{colour.lstrip('#').upper()}"


def vector_group_open(op, args, indent):
    if op == "translate":
        attrs = f'android:translateX="{args[0]:g}" android:translateY="{args[1] if len(args) > 1 else 0:g}"'
    elif op == "scale":
        sx = args[0]
        sy = args[1] if len(args) > 1 else sx
        attrs = f'android:scaleX="{sx:g}" android:scaleY="{sy:g}"'
    elif op == "rotate":
        cx, cy = (args[1], args[2]) if len(args) == 3 else (0, 0)
        attrs = f'android:rotation="{args[0]:g}" android:pivotX="{cx:g}" android:pivotY="{cy:g}"'
    else:
        raise ValueError(f"unsupported transform {op}")
    return f"{indent}<group {attrs}>"


def vector_items(el, indent):
    out = []
    ops = transforms(el.get("transform"))
    for op, args in ops:
        out.append(vector_group_open(op, args, indent))
        indent += "    "
    tag = el.tag.replace(SVG_NS, "")
    if tag in ("g", "svg"):
        for child in el:
            out += vector_items(child, indent)
    else:
        opacity = float(el.get("opacity", 1))
        attrs = [f'android:pathData="{shape_path(el)}"']
        if el.get("fill", "#000") != "none":
            attrs.append(f'android:fillColor="{argb(el.get("fill"), opacity)}"')
        if el.get("stroke"):
            attrs.append(f'android:strokeColor="{argb(el.get("stroke"), opacity)}"')
            attrs.append(f'android:strokeWidth="{float(el.get("stroke-width", 1)):g}"')
            if el.get("stroke-linecap"):
                attrs.append(f'android:strokeLineCap="{el.get("stroke-linecap")}"')
            if el.get("stroke-linejoin"):
                attrs.append(f'android:strokeLineJoin="{el.get("stroke-linejoin")}"')
        sep = f"\n{indent}    "
        out.append(f"{indent}<path{sep}{sep.join(attrs)} />")
    for _ in ops:
        indent = indent[:-4]
        out.append(f"{indent}</group>")
    return out


def vector(body_xml):
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->",
        HEADER,
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:tools="http://schemas.android.com/tools"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108"',
        '    tools:ignore="VectorPath">',
        *body_xml,
        "</vector>",
        "",
    ])


def colour_vector(inner):
    root = ET.fromstring(art.svg(inner))
    return vector([line for child in root for line in vector_items(child, "    ")])


# ---------- Monochrome layer: ink minus paper, as one even-odd path ----------

def flatten(d):
    """Subpaths of an SVG path made of M, L, H, V, Q, Z (absolute or relative) as point lists."""
    tokens = re.findall(r"[MLHVQZmlhvqz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    subpaths, points, closed = [], [], False
    x = y = 0.0
    i, cmd = 0, None
    while i < len(tokens):
        if re.match(r"[A-Za-z]", tokens[i]):
            cmd = tokens[i]
            i += 1
            if cmd in "Zz":
                closed = True
                continue
        rel = cmd.islower()
        c = cmd.upper()
        n = {"M": 2, "L": 2, "H": 1, "V": 1, "Q": 4}[c]
        v = [float(t) for t in tokens[i:i + n]]
        i += n
        if c == "M":
            if points:
                subpaths.append((points, closed))
            x, y = (x + v[0], y + v[1]) if rel else (v[0], v[1])
            points, closed = [(x, y)], False
            cmd = "l" if rel else "L"
        elif c == "L":
            x, y = (x + v[0], y + v[1]) if rel else (v[0], v[1])
            points.append((x, y))
        elif c == "H":
            x = x + v[0] if rel else v[0]
            points.append((x, y))
        elif c == "V":
            y = y + v[0] if rel else v[0]
            points.append((x, y))
        elif c == "Q":
            qx, qy, ex, ey = (x + v[0], y + v[1], x + v[2], y + v[3]) if rel else v
            for k in range(1, CURVE_STEPS + 1):
                t = k / CURVE_STEPS
                points.append(((1 - t) ** 2 * x + 2 * (1 - t) * t * qx + t * t * ex,
                               (1 - t) ** 2 * y + 2 * (1 - t) * t * qy + t * t * ey))
            x, y = ex, ey
    if points:
        subpaths.append((points, closed))
    return subpaths


def shape_geometry(el):
    """(fill area, stroke area) of one element, before its transforms."""
    tag = el.tag.replace(SVG_NS, "")
    f = lambda name: float(el.get(name, 0))
    fill = el.get("fill", "#000") != "none"
    width = float(el.get("stroke-width", 1)) if el.get("stroke") else 0
    cap = 1 if el.get("stroke-linecap") == "round" else 2
    if tag == "path":
        parts = flatten(el.get("d"))
        area = unary_union([Polygon(p) for p, _ in parts if len(p) > 2]) if fill else None
        lines = [LineString(p + ([p[0]] if c else [])) for p, c in parts]
        stroke = unary_union([ln.buffer(width / 2, cap_style=cap, join_style=1) for ln in lines]) if width else None
        return area, stroke
    if tag in ("circle", "ellipse"):
        rx = f("r") if tag == "circle" else f("rx")
        ry = f("r") if tag == "circle" else f("ry")
        shape = affinity.scale(Point(f("cx"), f("cy")).buffer(1, 32), rx, ry)
    elif tag == "rect":
        x, y, w, h, r = f("x"), f("y"), f("width"), f("height"), f("rx")
        shape = box(x + r, y + r, x + w - r, y + h - r).buffer(r, 8) if r else box(x, y, x + w, y + h)
    else:
        raise ValueError(f"unsupported element {tag}")
    stroke = shape.exterior.buffer(width / 2, join_style=1) if width else None
    return (shape if fill else None), stroke


def apply(geom, ops):
    for op, args in reversed(ops):
        if op == "translate":
            geom = affinity.translate(geom, args[0], args[1] if len(args) > 1 else 0)
        elif op == "scale":
            geom = affinity.scale(geom, args[0], args[1] if len(args) > 1 else args[0], origin=(0, 0))
        elif op == "rotate":
            origin = (args[1], args[2]) if len(args) == 3 else (0, 0)
            geom = affinity.rotate(geom, args[0], origin=origin)
    return geom


def paint(el, ink, outer_ops):
    """Painter's algorithm: ink colours add to the shape, paper colours cut holes in it."""
    ops = outer_ops + transforms(el.get("transform"))
    tag = el.tag.replace(SVG_NS, "")
    if tag in ("g", "svg"):
        for child in el:
            ink = paint(child, ink, ops)
        return ink
    area, stroke = shape_geometry(el)
    for geom, colour in ((area, el.get("fill")), (stroke, el.get("stroke"))):
        if geom is None or geom.is_empty:
            continue
        geom = apply(geom, ops)
        ink = ink.union(geom) if colour == art.INK else ink.difference(geom)
    return ink


def mono_vector(inner):
    root = ET.fromstring(art.svg(inner))
    shape = paint(root, Polygon(), [])
    # Keep the layer inside the icon and drop slivers thinner than a pixel at 432 px
    shape = shape.intersection(box(0, 0, 108, 108)).simplify(0.03)
    polygons = shape.geoms if isinstance(shape, MultiPolygon) else [shape]
    ring = lambda coords: "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in list(coords)[:-1]) + " Z"
    data = " ".join(ring(r.coords) for p in polygons for r in [p.exterior, *p.interiors])
    return vector([
        "    <path",
        '        android:fillColor="#FFFFFFFF"',
        '        android:fillType="evenOdd"',
        f'        android:pathData="{data}" />',
    ])


# ---------- Output ----------

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def colour_resource(colour, comment):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->\n'
            f"{HEADER}\n<!-- {comment} -->\n<resources>\n"
            f'    <color name="icon_background">{colour}</color>\n</resources>\n')


def main():
    main_res = ROOT / "app/src/main/res"
    debug_res = ROOT / "app/src/debug/res"
    write(main_res / "drawable/ic_launcher_foreground.xml", colour_vector(art.foreground(art.RELEASE)))
    write(main_res / "drawable/ic_launcher_monochrome.xml", mono_vector(art.foreground(art.MONO)))
    write(main_res / "values/icon_colors.xml", colour_resource(art.RELEASE["bg"], "Background of the launcher icon"))
    write(main_res / "mipmap-anydpi/ic_launcher.xml", "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->",
        HEADER,
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
        '    <background android:drawable="@color/icon_background" />',
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />',
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />',
        "</adaptive-icon>",
        "",
    ]))
    write(debug_res / "drawable/ic_launcher_foreground.xml",
          colour_vector(art.foreground(art.DEBUG, debug=True)))
    write(debug_res / "drawable/ic_launcher_monochrome.xml",
          mono_vector(art.foreground(art.MONO, debug=True, badge_colours=art.MONO_BADGE)))
    write(debug_res / "values/icon_colors.xml",
          colour_resource(art.DEBUG["bg"], "Debug builds only (Formica-D): draft grey"))

    # Store icon: the part a launcher shows, on a rounded square (as in SoftRing)
    full = (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="16 16 76 76">'
            f'<rect x="16" y="16" width="76" height="76" rx="16.72" fill="{art.RELEASE["bg"]}"/>'
            f'{art.foreground(art.RELEASE)}</svg>')
    write(ROOT / "art/icon.svg", full + "\n")
    try:
        import cairosvg
    except (ImportError, OSError) as e:
        print(f"Vector files written. Store PNG NOT updated (cairosvg unavailable: {e}).")
        return 0
    png = ROOT / "fastlane/metadata/android/en-US/images/icon.png"
    png.parent.mkdir(parents=True, exist_ok=True)
    cairosvg.svg2png(bytestring=full.encode(), write_to=str(png), output_width=512, output_height=512)
    print("Icon files written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
